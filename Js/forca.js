    // Variáveis principais do jogo
    let palavraEscolhida="";
    let categoriaEscolhida="";
    let dicaEscolhida="";
    let letrasAcertadas=[];
    let erros=0;
    let jogoAcabou=false;
    let dicaUsada=false;
    
    // Elementos do HTML
    let palavra=document.getElementById("palavra");
    let categoria=document.getElementById("categoria");
    let dica=document.getElementById("dica");
    let errosTexto=document.getElementById("erros");
    let letras=document.getElementById("letras");
    let botaoDica=document.getElementById("botaoDica");
    let botaoReiniciar=document.getElementById("botaoReiniciar");
    let resultado=document.getElementById("resultado");
    let resultadoTitulo=document.getElementById("resultadoTitulo");
    let resultadoMensagem=document.getElementById("resultadoMensagem");
    let jogarNovamente=document.getElementById("jogarNovamente");
    
    // Inicia ou reinicia o jogo
    function iniciarJogo(){
    let numero=Math.floor(Math.random()*palavras.length);
    let palavraAtual=palavras[numero];
    
    palavraEscolhida=palavraAtual.palavra;
    categoriaEscolhida=palavraAtual.categoria;
    dicaEscolhida=palavraAtual.dica;
    
    letrasAcertadas=[];
    erros=0;
    jogoAcabou=false;
    dicaUsada=false;
    
    categoria.innerHTML=categoriaEscolhida;
    dica.innerHTML="";
    errosTexto.innerHTML="Erros: 0 / 6";
    resultado.style.display="none";
    botaoDica.disabled=false;
    botaoDica.innerHTML="💡 PEDIR DICA";
    
    mostrarPalavra();
    criarLetras();
    }
    
    // Mostra a palavra com "_" nas letras que ainda não foram descobertas
    function mostrarPalavra(){
    palavra.innerHTML="";
    
    for(let i=0;i<palavraEscolhida.length;i++){
    let letra=palavraEscolhida[i];
    let espaco=document.createElement("span");
    
    if(letrasAcertadas.includes(letra)){
    espaco.innerHTML=letra;
    }else{
    espaco.innerHTML="_";
    }
    
    palavra.appendChild(espaco);
    }
    }
    
    // Cria os botões com as letras do alfabeto
    function criarLetras(){
    letras.innerHTML="";
    let alfabeto="ABCDEFGHIJKLMNOPQRSTUVWXYZ";
    
    for(let i=0;i<alfabeto.length;i++){
    let botao=document.createElement("button");
    botao.innerHTML=alfabeto[i];
    
    botao.addEventListener("click",function(){
    escolherLetra(alfabeto[i],botao);
    });
    
    letras.appendChild(botao);
    }
    }
    
    // Verifica se a letra escolhida está na palavra
    function escolherLetra(letra,botao){
    if(jogoAcabou==true){
    return;
    }
    
    botao.disabled=true;
    
    if(palavraEscolhida.includes(letra)){
    letrasAcertadas.push(letra);
    mostrarPalavra();
    verificarVitoria();
    }else{
    erros++;
    errosTexto.innerHTML="Erros: "+erros+" / 6";
    
    if(erros>=6){
    mostrarResultado(false);
    }
    }
    }
    
    // Mostra a dica uma única vez
    function pedirDica(){
    if(jogoAcabou==true){
    return;
    }
    
    if(dicaUsada==true){
    return;
    }
    
    dica.innerHTML="💡 "+dicaEscolhida;
    dicaUsada=true;
    botaoDica.disabled=true;
    botaoDica.innerHTML="DICA UTILIZADA";
    }
    
    // Verifica se todas as letras foram acertadas
    function verificarVitoria(){
    for(let i=0;i<palavraEscolhida.length;i++){
    if(!letrasAcertadas.includes(palavraEscolhida[i])){
    return;
    }
    }
    
    mostrarResultado(true);
    }
    
    // Mostra a mensagem de vitória ou derrota
    function mostrarResultado(vitoria){
    jogoAcabou=true;
    resultado.style.display="flex";
    
    if(vitoria==true){
    resultadoTitulo.innerHTML="PARABÉNS!";
    resultadoMensagem.innerHTML="Você acertou a palavra!";
    }else{
    resultadoTitulo.innerHTML="VOCÊ PERDEU!";
    resultadoMensagem.innerHTML="A palavra era: "+palavraEscolhida;
    }
    }
    
    // Reinicia o jogo
    function reiniciar(){
    iniciarJogo();
    }
    
    // Eventos dos botões
    botaoDica.addEventListener("click",pedirDica);
    botaoReiniciar.addEventListener("click",reiniciar);
    jogarNovamente.addEventListener("click",reiniciar);
    
    // Começa o jogo
    iniciarJogo();